// The agent (D10): one Claude pod in agentpod, chatting from the dashboard.
// The pod may write only the personal layer; it reads the core code and docs, and drives
// everything else through the `life` CLI with its own "agent" token.

import { chmodSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createToken, deleteTokens } from "./auth";
import { APP, HOST, MODEL, PORT, paths } from "./config";
import { core, tables } from "./db";
import { broadcast } from "./events";
import { dropVersion, readLayout, snapshot, stateHash } from "./layer";
import { type Agentpod, AgentpodError, NotApprovedError, NotInstalledError, type PodEvent, connect } from "./vendor/agentpod";

const POD = "life";
const toml = (s: string) => JSON.stringify(s);

/** Writes the agentpod project, the `life` wrapper the pod runs, and a fresh agent token. */
export function writeAgentProject() {
  mkdirSync(paths.agentCli, { recursive: true });
  const bun = process.execPath;
  const life = join(paths.agentCli, "life");

  deleteTokens("agent");
  const url = `http://${HOST === "0.0.0.0" ? "127.0.0.1" : HOST}:${PORT}`;
  writeFileSync(join(paths.agentCli, "config.json"), JSON.stringify({ url, token: createToken("agent", "agent") }) + "\n", { mode: 0o600 });
  chmodSync(join(paths.agentCli, "config.json"), 0o600);
  writeFileSync(life, `#!/bin/sh\nexec ${toml(bun)} ${toml(join(paths.src, "cli.ts"))} --config ${toml(join(paths.agentCli, "config.json"))} "$@"\n`);
  chmodSync(life, 0o755);

  writeFileSync(
    join(paths.agent, "apod.toml"),
    `# Generated by life at startup (src/agent.ts). Don't edit: it's rewritten on every start.

[team]
name = "life"
entry = [${toml(POD)}]

[limits]
max_depth = 1
max_calls = 1
timeout_secs = 1200

[pods.${POD}]
harness = "claude"
model = ${toml(MODEL)}
instructions = "You are the agent inside the user's Life dashboard. apods.md explains how it works; follow it."
windows = [
  { path = ${toml(paths.layer)}, access = "rw" },
  { path = ${toml(paths.agentCli)}, access = "ro" },
  { path = ${toml(paths.src)}, access = "ro" },
  { path = ${toml(paths.docs)}, access = "ro" },
  { path = ${toml(dirname(bun))}, access = "ro" },
]
`,
  );

  const guide = readFileSync(join(paths.docs, "agent.md"), "utf8")
    .replaceAll("{{LIFE}}", life)
    .replaceAll("{{LAYER}}", paths.layer)
    .replaceAll("{{KIT}}", join(paths.src, "web", "kit", "index.tsx"))
    .replaceAll("{{DOCS}}", paths.docs);
  writeFileSync(join(paths.agent, "apods.md"), guide);
}

// ---------- the connection ----------

let ap: Agentpod | null = null;
let connecting: Promise<Agentpod> | null = null;

async function engine(): Promise<Agentpod> {
  if (ap) return ap;
  connecting ??= connect({ app: APP, project: paths.agent })
    .then((a) => {
      ap = a;
      return a;
    })
    .finally(() => {
      connecting = null;
    });
  return connecting;
}

function forget() {
  ap?.close();
  ap = null;
}

/** Plain words for what went wrong, with what to do about it. */
function explain(e: unknown): string {
  if (e instanceof NotInstalledError) return "agentpod isn't installed on this machine, so the agent can't run. Install agentpod (`apod`), then try again.";
  if (e instanceof NotApprovedError)
    return `Life isn't approved in agentpod yet. On this machine, in a terminal, run:\n\n\`${e.approveCommand} --name ${APP.name}\`\n\nThen send your message again.`;
  const msg = (e as Error)?.message ?? String(e);
  if (/approv/i.test(msg) && /team|apod\.toml|grant/i.test(msg))
    return `agentpod needs you to approve the agent's access. On this machine, in a terminal, run:\n\n\`apod team -C ${paths.agent} --approve\`\n\nThen send your message again.\n\n(${msg})`;
  return `The agent couldn't run: ${msg}`;
}

// ---------- chat turns ----------

export type ChatMessage = { id: number; role: "user" | "agent"; text: string; ts: number; tools: string[]; version: number | null; error: boolean };

function row(r: any): ChatMessage {
  return { id: r.id, role: r.role, text: r.text, ts: r.ts, tools: r.tools ? JSON.parse(r.tools) : [], version: r.version ?? null, error: !!r.error };
}

export function history(limit = 100): ChatMessage[] {
  return core.query("SELECT * FROM (SELECT * FROM chat ORDER BY id DESC LIMIT ?) ORDER BY id").all(limit).map(row);
}

function save(m: Omit<ChatMessage, "id" | "ts">): ChatMessage {
  const r = core
    .query("INSERT INTO chat (role, text, ts, tools, version, error) VALUES (?, ?, ?, ?, ?, ?) RETURNING *")
    .get(m.role, m.text, Date.now(), m.tools.length ? JSON.stringify(m.tools) : null, m.version, m.error ? 1 : 0);
  const msg = row(r);
  broadcast({ type: "chat", message: msg });
  return msg;
}

export function clearHistory() {
  core.exec("DELETE FROM chat");
  broadcast({ type: "chat", message: null });
}

/** A short, human line for a tool call, e.g. "Edited widgets/water.tsx" or "Ran life db exec …".
 * agentpod already sends `input` as the tool's most telling field (the command, the file path…). */
function describeTool(name: string, input: string): string {
  const short = (s: string) => {
    const lines = s.replaceAll(join(paths.agentCli, "life"), "life").replaceAll(paths.layer + "/", "").split("\n");
    const first = lines[0]!.length > 100 ? lines[0]!.slice(0, 99) + "…" : lines[0]!;
    return lines.length > 1 && !first.endsWith("…") ? first + " …" : first;
  };
  switch (name) {
    case "Bash":
      return `Ran ${short(input)}`;
    case "Write":
      return `Wrote ${short(input)}`;
    case "Edit":
    case "MultiEdit":
      return `Edited ${short(input)}`;
    case "Read":
      return `Read ${short(input)}`;
    case "Glob":
    case "Grep":
      return `Searched for ${short(input)}`;
    default:
      return `Used ${name}`;
  }
}

function context(message: string): string {
  const past = history(13).slice(0, -1);
  let widgets = "(couldn't read layout.json)";
  try {
    const l = readLayout();
    widgets = l.widgets.length ? l.widgets.map((w) => `${w.id} ("${w.title}", span ${w.span})`).join(", ") : "none yet";
  } catch {}
  const t = tables();
  const lines = [
    past.length ? "## Recent conversation\n" + past.map((m) => `${m.role === "user" ? "User" : "You"}: ${m.text.length > 800 ? m.text.slice(0, 800) + "…" : m.text}`).join("\n\n") : "",
    `## The dashboard now\nWidgets: ${widgets}\nTables in custom.db: ${t.length ? t.map((x) => `${x.name} (${x.rows} rows)`).join(", ") : "none yet"}`,
    `## The user says\n${message}`,
  ];
  return lines.filter(Boolean).join("\n\n");
}

let busy = false;

export function agentStatus() {
  return { busy, connected: ap !== null, model: MODEL };
}

/** Starts a turn in the background; progress and the answer arrive as events and chat messages. */
export function send(message: string): { started: boolean } {
  message = message.trim();
  if (!message) throw new Error("say something");
  if (busy) throw new Error("the agent is still working on the last message");
  busy = true;
  save({ role: "user", text: message, tools: [], version: null, error: false });
  broadcast({ type: "turn", state: "start" });
  turn(message).finally(() => {
    busy = false;
  });
  return { started: true };
}

async function turn(message: string) {
  const before = stateHash();
  const version = snapshot(`before: ${message}`, before);
  const tools: string[] = [];
  let text = "";
  let error = false;
  try {
    const a = await engine();
    const out = await a.call(POD, context(message), {
      onEvent: (e: PodEvent) => {
        if (e.kind === "tool") {
          const t = describeTool(e.name, e.input);
          tools.push(t);
          broadcast({ type: "agent", kind: "tool", text: t });
        } else if (e.kind === "text" && e.text.trim()) broadcast({ type: "agent", kind: "text", text: e.text });
        else if (e.kind === "log") broadcast({ type: "agent", kind: "log", text: e.text });
      },
    });
    text = out.text.trim() || "(no answer)";
    error = out.error;
  } catch (e) {
    if (!(e instanceof AgentpodError) || e.code === -32003) forget();
    text = explain(e);
    error = true;
  }
  const changed = stateHash() !== before;
  if (!changed) dropVersion(version);
  save({ role: "agent", text, tools, version: changed ? version : null, error });
  broadcast({ type: "layer" });
  broadcast({ type: "data" });
  broadcast({ type: "turn", state: "end", error });
}

export async function stop(): Promise<number> {
  if (!ap) return 0;
  return ap.stop(POD);
}
